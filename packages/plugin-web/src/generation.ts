import { CormiError } from '@cormijs/core';
import { mkdir, open, realpath, unlink } from 'node:fs/promises';
import { lstatSync, readFileSync, renameSync, type Stats } from 'node:fs';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';

export const GENERATED_HEADER = '// Generated by cormi. Do not edit.\n';
function existing(file: string): string | undefined {
  try {
    const stat = lstatSync(file);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new CormiError('GENERATED_PATH_INVALID', 'Generated target must be a regular file.');
    const text = readFileSync(file, 'utf8');
    if (!text.startsWith(GENERATED_HEADER)) throw new CormiError('GENERATED_NOT_OWNED', 'Refusing to overwrite an unowned generated entry.');
    return text;
  } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw error; }
}
/** Only this single executable entry is published atomically; no cross-file transaction is claimed. */
export class AtomicEntry {
  private constructor(readonly directory: string, private readonly identity: Stats) {}
  static async open(root: string): Promise<AtomicEntry> {
    root = await realpath(root);
    const directory = join(root, '.cormi');
    try { await mkdir(directory); } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error; }
    const info = lstatSync(directory);
    if (!info.isDirectory() || info.isSymbolicLink() || await realpath(directory) !== directory) throw new CormiError('GENERATED_PATH_INVALID', '.cormi must be a real project directory.');
    return new AtomicEntry(directory, info);
  }
  async publish(body: string, current: () => boolean): Promise<boolean> {
    const content = GENERATED_HEADER + body, target = join(this.directory, 'app.tsx');
    const before = existing(target);
    if (!current()) throw new CormiError('STALE_GENERATION', 'Generation is no longer current.');
    if (before === content) return false;
    const temporary = join(this.directory, `.app-${randomUUID()}.tmp`);
    let created = false;
    try {
      const handle = await open(temporary, 'wx', 0o600); created = true;
      try { await handle.writeFile(content); await handle.sync(); } finally { await handle.close(); }
      // No await between the revision fence and rename: an accepted new revision cannot slip in.
      const now = lstatSync(this.directory);
      if (now.isSymbolicLink() || now.dev !== this.identity.dev || now.ino !== this.identity.ino) throw new CormiError('GENERATED_PATH_INVALID', 'Generation directory identity changed.');
      if (existing(target) !== before) throw new CormiError('GENERATED_CONCURRENT_WRITE', 'Entry changed outside the active generation session.');
      if (!current()) throw new CormiError('STALE_GENERATION', 'Superseded before commit.');
      renameSync(temporary, target); created = false; return true;
    } finally { if (created) await unlink(temporary).catch(error => { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }); }
  }
}
export interface GenerationResult { readonly revision: number; readonly status: 'changed' | 'unchanged' | 'superseded' }
interface Job<T> {
  revision: number; compute: (signal: AbortSignal) => Promise<T>;
  resolve: (result: GenerationResult) => void; reject: (error: unknown) => void;
}
/** One consumer, one latest pending job. Abort is advisory; stale results can never commit. */
export class RevisionQueue<T> {
  private revision = 0;
  private closed = false;
  private pending?: Job<T>;
  private active?: AbortController;
  private draining?: Promise<void>;
  constructor(private readonly commit: (value: T, current: () => boolean) => Promise<boolean>) {}
  enqueue(compute: Job<T>['compute']): Promise<GenerationResult> {
    if (this.closed) return Promise.reject(new CormiError('GENERATOR_CLOSED', 'Generation session is closed.'));
    const revision = ++this.revision;
    this.active?.abort(new CormiError('STALE_GENERATION', 'New input supersedes active work.'));
    if (this.pending) this.pending.resolve({ revision: this.pending.revision, status: 'superseded' });
    const result = new Promise<GenerationResult>((resolve, reject) => { this.pending = { revision, compute, resolve, reject }; });
    this.start(); return result;
  }
  private start(): void {
    if (this.draining) return;
    this.draining = this.drain().finally(() => { this.draining = undefined; if (this.pending) this.start(); });
  }
  private async drain(): Promise<void> {
    while (this.pending && !this.closed) {
      const job = this.pending; this.pending = undefined;
      const controller = this.active = new AbortController();
      const current = () => !this.closed && job.revision === this.revision && !controller.signal.aborted;
      try {
        const value = await job.compute(controller.signal);
        if (!current()) { job.resolve({ revision: job.revision, status: 'superseded' }); continue; }
        const changed = await this.commit(value, current);
        job.resolve({ revision: job.revision, status: current() ? changed ? 'changed' : 'unchanged' : 'superseded' });
      } catch (error) {
        if (!current()) job.resolve({ revision: job.revision, status: 'superseded' }); else job.reject(error);
      } finally { if (this.active === controller) this.active = undefined; }
    }
  }
  async close(): Promise<void> {
    this.closed = true; this.active?.abort(new CormiError('GENERATOR_CLOSED', 'Generation session closed.'));
    if (this.pending) { this.pending.resolve({ revision: this.pending.revision, status: 'superseded' }); this.pending = undefined; }
    await this.draining;
  }
}
