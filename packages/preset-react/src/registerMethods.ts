import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { lodash, Mustache, ServiceStage } from '@cormi/core'
import type { IApi, IWriteTmpFileOptions } from './types.ts'

/** Hooks applied by the preset (umi's `registerMethods`). */
export default (api: IApi) => {
  [
    'onGenerateFiles',
    'onBeforeCompiler',
    'onBuildComplete',
    'onBuildHtmlComplete',
    'onPatchRoute',
    'onPkgJSONChanged',
    'onPrepareBuildSuccess',
    'onDevCompileDone',
    'onCheckPkgJSON',
    'onCheckCode',
    'onCheckConfig',
    'onBeforeMiddleware',
    'addBeforeMiddlewares',
    'addLayouts',
    'addMiddlewares',
    'addApiMiddlewares',
    'addRuntimePlugin',
    'addRuntimePluginKey',
    'addPolyfillImports',
    'addPrepareBuildPlugins',
    'addEntryImportsAhead',
    'addEntryImports',
    'addEntryCodeAhead',
    'addEntryCode',
    'addExtraBabelPresets',
    'addExtraBabelPlugins',
    'addBeforeBabelPresets',
    'addBeforeBabelPlugins',
    'addHTMLMetas',
    'addHTMLLinks',
    'addHTMLStyles',
    'addHTMLHeadScripts',
    'addHTMLScripts',
    'addTmpGenerateWatcherPaths',
    'addOnDemandDeps',
    'addUIModules',
    'chainWebpack',
    'modifyEntry',
    'modifyHTMLFavicon',
    'modifyHTML',
    'modifyExportHTMLFiles',
    'modifyWebpackConfig',
    'modifyViteConfig',
    'modifyRendererPath',
    'modifyServerRendererPath',
    'modifyRoutes',
    'modifyBabelPresetOpts',
    'modifyTSConfig',
    'modifyUniBundler',
    'modifyUniBundlerOpts',
  ].forEach((name) => {
    api.registerMethod({ name })
  })

  api.registerMethod({
    name: 'writeTmpFile',
    fn(this: IApi, opts: IWriteTmpFileOptions) {
      if (this.service.stage < ServiceStage.runCommand) {
        throw new Error('api.writeTmpFile() should not execute in register stage.')
      }
      const absPath = join(
        this.paths.absTmpPath,
        this.plugin?.key && !opts.noPluginDir ? `plugin-${this.plugin.key}` : '',
        opts.path,
      )
      mkdirSync(dirname(absPath), { recursive: true })
      let content = opts.content
      if (content === undefined) {
        if (opts.tplPath && !existsSync(opts.tplPath)) {
          throw new Error(`opts.tplPath does not exists or is not a file.`)
        }
        const tpl = opts.tplPath ? readFileSync(opts.tplPath, 'utf8') : opts.tpl
        if (!tpl) throw new Error(`opts.tpl or opts.tplPath must be supplied.`)
        if (!lodash.isPlainObject(opts.context)) throw new Error(`opts.context must be plain object.`)
        content = Mustache.render(tpl, opts.context)
      }
      const isJsFile = /\.[cm]?[tj]sx?$/.test(absPath)
      content = [
        /\.tsx?$/.test(opts.path) && !opts.path.endsWith('.d.ts') && '// @ts-nocheck',
        isJsFile && '// This file is generated by Cormi automatically',
        isJsFile && '// DO NOT CHANGE IT MANUALLY!',
        content.trim(),
        '',
      ].filter(text => text !== false).join('\n')
      // unchanged files keep their mtime, so that the bundler does not reload them
      if (existsSync(absPath)) {
        const current = readFileSync(absPath, 'utf8')
        if (current.startsWith('// debug') || current === content) return
      }
      writeFileSync(absPath, content, 'utf8')
    },
  })
}
